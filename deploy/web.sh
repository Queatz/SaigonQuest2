#!/usr/bin/env bash
# Build the production web app locally and publish it behind nginx + Traefik.
# Safe to re-run. Does not wipe the host, certificates, or unrelated sites.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
# shellcheck source=deploy/lib.sh
source "$ROOT/deploy/lib.sh"

usage() {
  cat <<'EOF'
Usage: deploy/web.sh [--skip-init]

Builds the Kotlin/JS production bundle locally, uploads it, and serves it with
nginx behind Traefik TLS. /api and /media are proxied to the server domain.

  --skip-init   Skip package install, firewall, and nginx/Traefik setup.
                Still uploads the site and runs the health check.

Config: deploy/web.env (see deploy/web.env.example)
Deploy the API first so the proxied health check can succeed.
EOF
}

SKIP_INIT=0
for arg in "$@"; do
  case "$arg" in
    --skip-init) SKIP_INIT=1 ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $arg" ;;
  esac
done

command -v curl >/dev/null 2>&1 || die "curl is required locally"
command -v rsync >/dev/null 2>&1 || die "rsync is required locally"

cd "$ROOT"
load_env_file "$ROOT/deploy/web.env"
require_var SSH_HOST
require_var SSH_USER
require_var WEB_DOMAIN
require_var SERVER_DOMAIN
API_MODE=$(printf '%s' "${API_MODE:-proxy}" | tr '[:upper:]' '[:lower:]')
WEB_ROOT=${WEB_ROOT:-/var/www/saigonquest}
NGINX_BIND=${NGINX_BIND:-127.0.0.1:8081}
SERVER_UPSTREAM=${SERVER_UPSTREAM:-https://$SERVER_DOMAIN}
SERVER_UPSTREAM=${SERVER_UPSTREAM%/}
SSH_PORT=${SSH_PORT:-22}
validate_domain "$WEB_DOMAIN"
validate_domain "$SERVER_DOMAIN"
assert_safe_dir "$WEB_ROOT" WEB_ROOT
[[ "$NGINX_BIND" == *:* ]] || die "NGINX_BIND must be host:port"
case "$API_MODE" in
  proxy|direct) ;;
  *) die "API_MODE must be proxy or direct" ;;
esac
if [[ "$SKIP_INIT" -eq 0 ]]; then
  require_var ACME_EMAIL
fi
build_ssh

origin=""
if [[ "$API_MODE" == "direct" ]]; then
  origin="https://${SERVER_DOMAIN}"
fi

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT

log "Building the production web app"
./gradlew clean :app:webApp:jsBrowserProductionWebpack
js=$(find "$ROOT/app/webApp/build" -type f -name webApp.js -path '*productionExecutable*' -print -quit)
resources="$ROOT/app/webApp/build/processedResources/js/main"
[[ -n "$js" && -f "$resources/index.html" ]] || die "production build did not produce webApp.js and index.html"
cp -a "$resources/." "$stage/"
cp -a "$(dirname "$js")/." "$stage/"
cat > "$stage/sq-config.js" <<EOF
// Generated by deploy/web.sh. Empty origin means same-origin /api and /media.
window.SAIGON_SERVER_ORIGIN = $(json_quote "$origin");
window.SAIGON_SERVER_DOMAIN = $(json_quote "$SERVER_DOMAIN");
EOF
[[ -f "$stage/index.html" && -f "$stage/webApp.js" && -f "$stage/styles.css" && -f "$stage/manifest.json" && -f "$stage/sw.js" ]] || die "web stage is incomplete"
grep -q 'sq-config.js' "$stage/index.html" || die "index.html does not load sq-config.js"

if [[ "$SKIP_INIT" -eq 0 ]]; then
  log "Configuring nginx and Traefik on ${SSH_TARGET}"
  TRAEFIK_VERSION=${TRAEFIK_VERSION:-v3.7.13}
  stage_traefik_tarball
  send_remote "$ROOT" \
    "WEB_DOMAIN=$WEB_DOMAIN" \
    "SERVER_DOMAIN=$SERVER_DOMAIN" \
    "SERVER_UPSTREAM=$SERVER_UPSTREAM" \
    "WEB_ROOT=$WEB_ROOT" \
    "NGINX_BIND=$NGINX_BIND" \
    "ACME_EMAIL=${ACME_EMAIL:-}" \
    "SSH_PORT=$SSH_PORT" \
    "TRAEFIK_VERSION=$TRAEFIK_VERSION" \
    "TRAEFIK_TARBALL=${TRAEFIK_TARBALL:-}" \
    "TRAEFIK_DYNAMIC_DIR=${TRAEFIK_DYNAMIC_DIR:-}" <<'REMOTE'
set -euo pipefail
require_root
: "${WEB_DOMAIN:?}"
: "${SERVER_DOMAIN:?}"
: "${SERVER_UPSTREAM:?}"
: "${WEB_ROOT:?}"
: "${NGINX_BIND:?}"

ensure_base_packages
free_edge_ports
ensure_nginx_upgrade_map >/dev/null
traefik_state=$(ensure_traefik) || die "Traefik setup failed"
install -d -m 755 "$WEB_ROOT"

ssl_directives=""
if [[ "$SERVER_UPSTREAM" == https://* ]]; then
  ssl_directives="proxy_ssl_server_name on;
        proxy_ssl_name ${SERVER_DOMAIN};"
fi

write_if_changed /etc/nginx/sites-available/saigonquest-web 644 >/dev/null <<EOF
server {
    listen ${NGINX_BIND};
    server_name ${WEB_DOMAIN};
    root ${WEB_ROOT};
    index index.html;
    client_max_body_size 20m;

    location /api/ {
$(proxy_location "$SERVER_UPSTREAM" "$SERVER_DOMAIN" "$ssl_directives")
    }

    location /media/ {
$(proxy_location "$SERVER_UPSTREAM" "$SERVER_DOMAIN" "$ssl_directives")
    }

    location / {
        add_header Cache-Control "no-cache";
        try_files \$uri \$uri/ /index.html;
    }
}
EOF
ln -sfn /etc/nginx/sites-available/saigonquest-web /etc/nginx/sites-enabled/saigonquest-web
write_traefik_route web "$WEB_DOMAIN" "http://${NGINX_BIND}" >/dev/null
reload_nginx
start_traefik "$traefik_state"
open_edge_ports
REMOTE
else
  log "Skipping server init"
fi

log "Uploading the web app to ${WEB_ROOT}"
remote_tmp="/tmp/saigonquest-web-$$"
ssh "${SSH_OPTS[@]}" "$SSH_TARGET" "mkdir -p $(printf '%q' "$remote_tmp")"
rsync -az --delete -e "$(rsync_rsh)" "$stage/" "${SSH_TARGET}:${remote_tmp}/"
send_remote "$ROOT" "WEB_ROOT=$WEB_ROOT" "REMOTE_TMP=$remote_tmp" <<'REMOTE'
set -euo pipefail
require_root
: "${WEB_ROOT:?}"
: "${REMOTE_TMP:?}"
install -d -m 755 "$WEB_ROOT"
rsync -a --delete "$REMOTE_TMP/" "$WEB_ROOT/"
chmod -R a+rX "$WEB_ROOT"
rm -rf "$REMOTE_TMP"
REMOTE

if [[ "$SKIP_INIT" -eq 0 ]]; then
  send_remote "$ROOT" <<'REMOTE'
set -euo pipefail
require_root
reload_nginx
REMOTE
fi

log "Checking https://${WEB_DOMAIN}/"
health_check "https://${WEB_DOMAIN}/" "Web"
config_body=$(curl -fsS -m 20 "https://${WEB_DOMAIN}/sq-config.js")
printf '%s\n' "$config_body" | grep -F "$SERVER_DOMAIN" >/dev/null \
  || die "sq-config.js does not mention ${SERVER_DOMAIN}"
log "Web knows the server domain: ${SERVER_DOMAIN}"
health_check "https://${WEB_DOMAIN}/api/health" "Web API proxy"
